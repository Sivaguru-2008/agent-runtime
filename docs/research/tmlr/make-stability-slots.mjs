#!/usr/bin/env node
/**
 * Result slots for the scoring-context stability experiment
 * (research/effect-identity/results/scoring_stability.json) -> generated/stability.tex.
 * Every interval is printed in the form checkPaper.js verifies; fails if the
 * results file is absent, so the build cannot produce a PDF without it.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "..", "..", "..", "research", "effect-identity", "results", "scoring_stability.json");
if (!existsSync(src)) {
  if (process.argv.includes("--allow-pending")) {
    // Draft layout only: every slot prints a visible marker and no number.
    const names = ["stabNResidual", "stabNCal", "stabNTest", "stabFPIdenticalCount", "stabFPLarge", "stabFPSigned",
      ...["MP", "MF", "MM", "MR", "MT"].flatMap((t) => ["Thr", "Pool", "WS", "WSCount", "Dedup"].map((k) => `stab${t}${k}`))];
    mkdirSync(resolve(here, "generated"), { recursive: true });
    writeFileSync(resolve(here, "generated", "stability.tex"),
      "%% PENDING — draft placeholders, not results.\n" + names.map((n) => `\\newcommand{\\${n}}{\\textbf{[pending]}}`).join("\n") + "\n");
    console.log("stability results absent: wrote PENDING placeholders (draft build only)");
    process.exit(0);
  }
  console.error("scoring_stability.json not present — run: node src/experiments/scoringStability.js --score && --evaluate (research/effect-identity)");
  process.exit(2);
}
const r = JSON.parse(readFileSync(src, "utf8"));
const iv = (x) => (x && x.ci95 && x.n > 0 ? `${(100 * x.value).toFixed(1)}\\%~[${(100 * x.ci95.lo).toFixed(1)}--${(100 * x.ci95.hi).toFixed(1)}]` : "n/a");
const cnt = (x) => (x && x.n > 0 ? `${x.successes} of ${x.n}` : "none");
const thr = (t) => (t === "Infinity" ? "$+\\infty$" : Number(t).toFixed(2));
const L = ["%% GENERATED by make-stability-slots.mjs from results/scoring_stability.json — do not edit."];
const def = (k, v) => L.push(`\\newcommand{\\${k}}{${v}}`);
def("stabNResidual", r.nResidual); def("stabNCal", r.nCal); def("stabNTest", r.nTest);
const C = { matchedPersisted: "MP", matchedFresh: "MF", mismatched: "MM", mismatchedReverse: "MR", mismatchedThirdScoring: "MT" };
for (const [k, tag] of Object.entries(C)) {
  const c = r.conditions[k];
  if (!c) continue;
  def(`stab${tag}Thr`, thr(c.tHi)); def(`stab${tag}Pool`, c.poolN);
  def(`stab${tag}WS`, iv(c.residualWrongSuppression)); def(`stab${tag}WSCount`, cnt(c.residualWrongSuppression));
  def(`stab${tag}Dedup`, iv(c.residualDedup));
}
const A = { freshVsPersisted: "FP", freshVsMultiCandidateRun: "FT", persistedVsMultiCandidateRun: "PT" };
for (const [k, tag] of Object.entries(A)) {
  const a = r.agreement[k];
  if (!a) continue;
  def(`stab${tag}Identical`, iv(a.identical)); def(`stab${tag}IdenticalCount`, cnt(a.identical));
  def(`stab${tag}Large`, cnt(a.largeChange));
  def(`stab${tag}Signed`, `${a.meanSignedDiff >= 0 ? "+" : ""}${a.meanSignedDiff.toFixed(3)}`);
}
mkdirSync(resolve(here, "generated"), { recursive: true });
writeFileSync(resolve(here, "generated", "stability.tex"), L.join("\n") + "\n");
console.log(`wrote generated/stability.tex (${L.length - 1} macros)`);
