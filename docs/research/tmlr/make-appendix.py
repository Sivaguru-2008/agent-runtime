"""Assemble sections/appendix.tex for the TMLR build from the AIJ sources.

Run once after editing the AIJ theory/framework/problem/fence/method sections:
    python docs/research/tmlr/make-appendix.py
Blocks are copied verbatim (citations converted to natbib parenthetical form);
nothing numeric is retyped, so the build's interval checker still sees them.
"""
import re, os
here = os.path.dirname(os.path.abspath(__file__))
aij = os.path.join(here, '..', 'aij', 'sections')
rd = lambda f: open(os.path.join(aij, f), encoding='utf8').read()

def env(text, name, label):
    """Return the environment `name` that carries \\label{label}."""
    for m in re.finditer(r'\\begin\{' + name + r'\}.*?\\end\{' + name + r'\}', text, re.S):
        if '\\label{' + label + '}' in m.group(0):
            return m.group(0)
    raise SystemExit(f'not found: {name} {label}')

def table_with(text, label):
    for m in re.finditer(r'(\{\\footnotesize\s*)?\\begin\{(table|longtable)\}.*?\\end\{\2\}\}?', text, re.S):
        if '\\label{' + label + '}' in m.group(0):
            return m.group(0)
    raise SystemExit(f'table not found: {label}')

citep = lambda s: re.sub(r'\\cite\{', r'\\citep{', s.replace('~\\cite{', ' \\cite{'))
problem, framework, theory, fence, method, related = (rd(f) for f in
    ['problem.tex', 'framework.tex', 'theory.tex', 'fence.tex', 'method.tex', 'related.tex'])

out = [r"""%% GENERATED by make-appendix.py from ../aij/sections — edit the AIJ source and re-run.
\section{Guarantees and deferred statements}\label{app:guarantees}

The phrase ``exactly-once'' conflates three claims that fail independently (Table~\ref{tab:guarantees}). A mechanism can be perfect at identity recognition (A) and fence-level commitment (B) yet still double-charge, because the failure in (C) happens after the provider accepts a request and before the commit row is durable, when no local code runs. We never claim (C) for the mechanism.
""",
    table_with(problem, 'tab:guarantees'),
    env(problem, 'proposition', 'prop:equivalence'),
    env(framework, 'proposition', 'prop:lattice'),
    env(theory, 'lemma', 'lem:scalefree'),
    r"The fence is a scale-free deterministic rule with $k=k^\ast=\lceil(n+1)(1-\alpha/m)\rceil$ and $\rho=n+1-k^\ast$. For the fence's threshold the worst case of Theorem~\ref{thm:tight} equals $\frac{m\rho}{n+1}-\mathbb{E}[(mB-1)_+]\le\frac{m\rho}{n+1}\le\alpha$, where $\mathbb{E}[(mB-1)_+]\le(m-1)\exp(-(1-\alpha)^2n/(2m))$.",
    env(theory, 'proposition', 'prop:impossible'),
    r"Zero error on a class therefore needs a decision that does not consult the score, which is what the certifier and the refuter are.",
    env(theory, 'proposition', 'prop:amo'),
    r"The commit window cannot be closed by any local mechanism, because during it the only record of the effect is at the provider. Without A7, two concurrent executions can both miss the log and dispatch; at most one commit row survives, so the duplicate is observable but not prevented.",
    env(theory, 'proposition', 'prop:compose'),
    env(theory, 'proposition', 'prop:structure'),
    r"""
\paragraph{Proofs of Propositions~\ref{prop:sound} and~\ref{prop:residual}}
The canonical branch fires only if $H(\kappa_t(x))=H(\kappa_t(x'))$ for a committed $x'$; by A2 this implies $\kappa_t(x)=\kappa_t(x')$ and by A5 $x\approx_t x'$. A committed effect whose projection differs is removed from $C$ before any judge call, so it is never the maximising candidate; if every committed effect differs, $C=\emptyset$ and the fence executes. For Proposition~\ref{prop:residual}: (i) the defining condition mentions only $\kappa_t$ and $\sigma_t$; (ii) a pair in $\equiv_\kappa$ is suppressed and by A5 is a true duplicate, and a pair in $\not\equiv_\sigma$ is executed and by A5$'$ is truly distinct; (iii) refinement enlarges $\equiv_\kappa$ and $\not\equiv_\sigma$, so their union grows and its complement shrinks.

\paragraph{Proof of Proposition~\ref{prop:dilemma}}
(a) As $n$ is an integer, $\lceil(n+1)(1-\alpha/m)\rceil\le n$ iff $m\le\alpha(n+1)$. (b) The $k$-th smallest of $n$ values is the $(n+1-k)$-th largest, and $n+1-\lceil(n+1)(1-\alpha/m)\rceil=\lfloor(n+1)\alpha/m\rfloor$. (c) The pool is the set of scored distinct calibration pairs in the jurisdiction, and by Proposition~\ref{prop:residual}(iii) the refined residual is contained in the original.
""",
    '\\input{generated/appendix-proofs}\n',
    r"""
\section{Additional material}\label{app:extra}

\paragraph{Assumptions}
Table~\ref{tab:assumptions} lists every assumption, its type and its status in the experiments. Structurally, the candidate set of a request is every effect committed in the same run for the same tool; duplicates across runs or across tools are out of scope.
""",
    table_with(theory, 'tab:assumptions'),
    '\n\\paragraph{Positioning}\n',
    table_with(related, 'tab:positioning'),
    r"""
\paragraph{Full decision procedure}
Algorithm~\ref{alg:fence} gives the complete procedure, including the commit path; Figure~\ref{fig:flow} shows the flow for one request.
""",
    env(fence, 'algorithm', 'alg:fence'),
    '\n\\input{figures/fig-flow}\n',
    '\n\\paragraph{Claims and evidence}\nTable~\\ref{tab:claims} maps each claim to the result that supports it and to what that result does not establish.\n',
    table_with(method, 'tab:claims'),
    '\n\\paragraph{Supplementary tables}\nThe remaining appendices reproduce the supplementary analyses and every generated table, including the multiple-candidate construction, resampling and seed-level splits, the schema ladder, crash points, the model panel, cost, the tightness computations, the authorisation instance and the class-conditional analysis.\n',
]
text = citep('\n\n'.join(out))
# The AIJ theory proves Theorem 1 in the main text; the TMLR main text does too.
open(os.path.join(here, 'sections', 'appendix.tex'), 'w', encoding='utf8').write(text)
print('wrote sections/appendix.tex', len(text.split()), 'words')
