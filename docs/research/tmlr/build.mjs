#!/usr/bin/env node
/**
 * Build the TMLR submission (anonymous, one document: main text + appendices).
 *
 *   node docs/research/tmlr/build.mjs            regenerate, check, compile main.pdf
 *   node docs/research/tmlr/build.mjs --check    regenerate and check only
 *
 * Data, figures and tables come from the same generators as the AIJ build, so
 * the two versions cannot quote different numbers. Order: regenerate figure
 * data, supplement tables and result slots from research/effect-identity/results;
 * copy them here; convert the AIJ supplement prose into appendices; then
 * checkPaper.js (every quoted interval), check-claims.mjs in TMLR mode (headline
 * numbers, stale strings, qualified "exactly-once", no leftover supplement
 * references), verify.js (artifact assertions), an anonymity scan, and only
 * then pdflatex/bibtex.
 */
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, copyFileSync, rmSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const aij = resolve(here, "..", "aij");
const artifact = resolve(here, "..", "..", "..", "research", "effect-identity");

function run(cmd, args, { cwd = here, quiet = false, allowFail = false, env } = {}) {
  const r = spawnSync(cmd, args, { cwd, encoding: "utf8", maxBuffer: 64 * 1024 * 1024, env: env ? { ...process.env, ...env } : process.env });
  if (!quiet && r.stdout) process.stdout.write(r.stdout);
  if (r.status !== 0 && !allowFail) {
    if (quiet && r.stdout) process.stdout.write(r.stdout.slice(-4000));
    process.stderr.write(r.stderr ?? "");
    throw new Error(`${cmd} ${args.join(" ")} exited ${r.status}`);
  }
  return r;
}
const copyDir = (from, to, filter = () => true) => {
  rmSync(to, { recursive: true, force: true });
  mkdirSync(to, { recursive: true });
  for (const e of readdirSync(from, { withFileTypes: true })) {
    if (e.isDirectory()) copyDir(join(from, e.name), join(to, e.name), filter);
    else if (filter(e.name)) copyFileSync(join(from, e.name), join(to, e.name));
  }
};
// Numeric-style \cite in reused AIJ text becomes a parenthetical natbib cite.
const citep = (s) => s.replace(/~\\cite\{/g, " \\citep{").replace(/\\cite\{/g, "\\citep{");

console.log("── 1. regenerate figure data, tables and result slots");
run("node", [resolve(aij, "tools", "make-figure-data.mjs")], { quiet: true });
run("node", [resolve(aij, "tools", "make-supp-tables.mjs")], { quiet: true });
run("node", [resolve(aij, "tools", "make-mclive-slots.mjs")], { quiet: true });
copyDir(resolve(aij, "figures"), resolve(here, "figures"));
copyDir(resolve(aij, "supplement", "tables"), resolve(here, "tables"), (n) => n.endsWith(".tex"));
mkdirSync(resolve(here, "generated"), { recursive: true });
copyFileSync(resolve(aij, "sections", "generated", "mclive.tex"), resolve(here, "generated", "mclive.tex"));
const DRAFT = process.argv.includes("--draft");
run("node", [resolve(here, "make-stability-slots.mjs"), ...(DRAFT ? ["--allow-pending"] : [])]);
if (DRAFT && !existsSync(resolve(here, "sections", "stability-interpretation.tex"))) {
  writeFileSync(resolve(here, "sections", "stability-interpretation.tex"), "\\textbf{[Interpretation pending the stability results.]}\n");
}
// A draft PDF is stamped so it cannot be mistaken for the submission.
writeFileSync(resolve(here, "generated", "draftmark.tex"), DRAFT
  ? "\\usepackage{eso-pic}\\AddToShipoutPictureBG{\\AtPageCenter{\\makebox(0,0){\\rotatebox{45}{\\scalebox{6}{\\color{red!12}DRAFT}}}}}\n"
  : "%% submission build: no draft mark\n");
copyFileSync(resolve(aij, "references.bib"), resolve(here, "references.bib"));
// Tables were written for the supplement: its labels and cross-references to the
// main text ("M-" prefix via xr-hyper) resolve locally in one document.
for (const f of readdirSync(resolve(here, "tables"))) {
  const p = resolve(here, "tables", f);
  writeFileSync(p, citep(readFileSync(p, "utf8")).replace(/\\ref\{M-/g, "\\ref{"));
}

console.log("── 2. supplement prose and proofs -> appendices");
writeFileSync(resolve(here, "generated", "appendix-proofs.tex"),
  "%% GENERATED by build.mjs from ../aij/sections/appendix-proofs.tex — edit the source, not this file.\n" +
  citep(readFileSync(resolve(aij, "sections", "appendix-proofs.tex"), "utf8")));
{
  const supp = readFileSync(resolve(aij, "supplement.tex"), "utf8");
  let body = supp.slice(supp.indexOf("\\maketitle") + "\\maketitle".length, supp.indexOf("\\end{document}"));
  // Drop sections that belong to the AIJ package, not to an anonymous TMLR
  // submission: the reading guide, the errata against the earlier long-form
  // version, and the artifact/repository description (replaced by an anonymous one).
  const drop = [/^\\section\{What this document contains.*?(?=^\\section\{)/ms, /^\\section\{Errata.*?(?=^\\section\{)/ms,
    /^\\section\{Artifact contents\}.*?(?=^\\section\{)/ms];
  for (const re of drop) body = body.replace(re, "");
  body = citep(body)
    .replace(/\\input\{supplement\/tables\//g, "\\input{tables/")
    .replace(/\\ref\{M-/g, "\\ref{")
    .replace(/the main paper's /g, "")
    .replace(/the main paper/g, "the main text")
    .replace(/\\label\{sec:s(\d+)\}/g, "\\label{app:s$1}");
  writeFileSync(resolve(here, "generated", "appendix-supplement.tex"),
    "%% GENERATED by build.mjs from ../aij/supplement.tex — edit the source, not this file.\n" + body);
}

const texFiles = () => {
  const walk = (rel) => (existsSync(resolve(here, rel)) ? readdirSync(resolve(here, rel), { withFileTypes: true })
    .flatMap((e) => (e.isDirectory() ? walk(`${rel}/${e.name}`) : e.name.endsWith(".tex") ? [`${rel}/${e.name}`] : [])) : []);
  return ["main.tex", ...walk("sections"), ...walk("tables"), ...walk("figures"), ...walk("generated")].map((f) => resolve(here, f));
};

console.log("── 3. quoted intervals (checkPaper.js)");
run("node", [resolve(artifact, "src", "experiments", "checkPaper.js"), "--manuscript", texFiles().join(",")]);

console.log("── 4. claims, stale strings, qualified guarantees (check-claims.mjs, TMLR mode)");
run("node", [resolve(aij, "tools", "check-claims.mjs")], { env: { CLAIMS_ROOT: here, CLAIMS_MODE: "tmlr" }, quiet: true });
console.log("claims ok");

console.log("── 5. artifact verifier (verify.js)");
run("node", [resolve(artifact, "src", "experiments", "verify.js")], { cwd: artifact, quiet: true });
console.log("verify ok");

console.log("── 6. anonymity");
{
  const bad = [/Sivaguru/i, /sivagurumurugan/i, /github\.com\/Sivaguru/i, /AgentRuntime/, /agent-runtime/i, /Chennai/i];
  const hits = [];
  for (const f of texFiles()) {
    const t = readFileSync(f, "utf8").replace(/%.*$/gm, "");
    for (const re of bad) if (re.test(t)) hits.push(`${f.slice(here.length + 1)}: ${re}`);
  }
  if (hits.length) { for (const h of hits) console.error(`  identifying string: ${h}`); throw new Error("anonymity check failed"); }
  console.log("no identifying strings");
}

if (process.argv.includes("--check")) { console.log("checks passed (--check: not compiling)"); process.exit(0); }

console.log("── 7. LaTeX");
const tex = ["-interaction=nonstopmode", "-halt-on-error", "-file-line-error", "main.tex"];
run("pdflatex", tex, { quiet: true });
run("bibtex", ["main"], { quiet: true });
run("pdflatex", tex, { quiet: true });
run("pdflatex", tex, { quiet: true });
const log = readFileSync(resolve(here, "main.log"), "utf8");
const problems = [...log.matchAll(/LaTeX Warning: (Reference|Citation) `([^']+)' .*undefined/g)].map((m) => `${m[1]} ${m[2]} undefined`);
const overfull = [...log.matchAll(/Overfull \\hbox \(([\d.]+)pt too wide\)/g)].map((m) => +m[1]).filter((w) => w > 20);
const pages = (log.match(/Output written on .*?\((\d+) pages?/) ?? [])[1];
// Page on which the references start = end of the main text for TMLR's purposes.
const aux = readFileSync(resolve(here, "main.aux"), "utf8");
const refPage = (aux.match(/\\newlabel\{sec:refs-start\}\{\{[^}]*\}\{(\d+)\}/) ?? [])[1];
console.log(`main.pdf: ${pages} pages (main text ends on p. ${refPage ?? "?"}); ${problems.length} undefined refs/cites; ${overfull.length} overfull boxes > 20pt`);
if (problems.length) { for (const p of [...new Set(problems)]) console.error(`  ${p}`); process.exit(1); }
console.log("build complete");
