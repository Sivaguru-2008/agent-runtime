import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync, rmSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadParaphrasePool, GENERATOR_MODEL } from "./wireParaphrases.js";
import { rate, fmtRate } from "../stats.js";
import { DEFAULT_JUDGE, groqAvailable, JUDGE_MODELS } from "../groq.js";
import { judgeKey } from "../judge.js";
import { CRASH_POINTS, COMMIT_WINDOW_POINTS } from "./crashPoints.js";

/**
 * The paraphrased crash/replay experiment, as N randomised trials over EIGHT
 * crash points and THREE OS processes per trial.
 *
 *   seed  → commits the wire
 *   crash → replays it paraphrased, hard-killed at the trial's crash point
 *   replay→ replays it paraphrased again, runs to completion
 *
 * Exactly-once = exactly one wire in the shared ledger at the end.
 *
 * The design is PAIRED: the syntactic and semantic modes see the identical
 * (paraphrase A, paraphrase B, crash point) draw, so the difference between
 * them is the mechanism and not the luck of the draw.
 *
 * The paraphrase pool is generated by a model from a DIFFERENT FAMILY than the
 * judge (`--pool-generator`), because a judge scoring its own family's
 * phrasings is partly measuring self-recognition. A previous version of this
 * experiment drew its pool from the judge's own model.
 *
 *   node src/experiments/crashReplay.js [--trials N] [--judge M]
 *        [--pool-generator M|handwritten] [--offline]
 */

const here = dirname(fileURLToPath(import.meta.url));
const base = resolve(here, "..", "..");
const workerPath = resolve(here, "crashWorker.js");
const live = !process.argv.includes("--offline");
const argAfter = (flag, fallback) => {
  const i = process.argv.indexOf(flag);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
};
const N_TRIALS = Number(argAfter("--trials", "48"));
const JUDGE_MODEL = argAfter("--judge", null);
const POOL_GENERATOR = argAfter("--pool-generator", GENERATOR_MODEL);
const OUT_NAME = argAfter("--out", "crash_replay.json");

const MODES = ["syntactic", "semantic"];
const PHASES = ["seed", "crash", "replay"];

const WINDOW_POINTS = COMMIT_WINDOW_POINTS;

/**
 * Use the thresholds the corpus evaluation actually calibrated, so the headline
 * experiment cannot silently run at a different operating point than the paper
 * reports. m = 1 here (one committed wire per run), so the pairwise and
 * multiplicity-corrected thresholds coincide.
 */
function calibratedThresholds() {
  const path = resolve(base, "results", "experiments.json");
  const fallback = live ? { tHi: 0.5, tLo: 0.3 } : { tHi: 0.83, tLo: 0.55 };
  if (!existsSync(path)) return { ...fallback, source: "fallback-defaults", judge: JUDGE_MODEL ?? DEFAULT_JUDGE };
  try {
    const exp = JSON.parse(readFileSync(path, "utf8"));
    const scorer = live ? (JUDGE_MODEL ? judgeKey(JUDGE_MODEL) : exp.primaryScorer) : "lexical";
    const cfg = exp.configs?.[`layered_${scorer}_alpha_0.05`];
    if (!cfg || !Number.isFinite(cfg.tHi)) return { ...fallback, source: "fallback-defaults", judge: JUDGE_MODEL ?? DEFAULT_JUDGE };
    const model = JUDGE_MODEL
      ?? Object.keys(JUDGE_MODELS).find((m) => judgeKey(m) === scorer)
      ?? DEFAULT_JUDGE;
    return { tHi: cfg.tHi, tLo: cfg.tLo, source: `layered_${scorer}_alpha_0.05`, judge: model };
  } catch {
    return { ...fallback, source: "fallback-defaults", judge: JUDGE_MODEL ?? DEFAULT_JUDGE };
  }
}

function runTrial(mode, dir, spec) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  writeFileSync(resolve(dir, "trial.json"), JSON.stringify(spec, null, 2));

  const args = (phase) => [workerPath, phase, dir, mode, ...(live ? ["--live"] : [])];
  const phaseOut = {};
  for (const phase of PHASES) {
    const p = spawnSync(process.execPath, args(phase), { encoding: "utf8" });
    // `crash` may exit 1 (it reached its crash point and was killed) or 0 (the
    // fence settled the dispatch first, so the point was never reached).
    const okCodes = phase === "crash" ? [0, 1] : [0];
    if (!okCodes.includes(p.status)) {
      throw new Error(`phase ${phase} (${mode}) exited ${p.status}: ${p.stderr?.slice(0, 400)}`);
    }
    const f = resolve(dir, `phase-${phase}-${mode}.json`);
    phaseOut[phase] = existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) : null;
  }

  const world = JSON.parse(readFileSync(resolve(dir, "world.json"), "utf8"));
  const fenceLog = JSON.parse(readFileSync(resolve(dir, `fence-${mode}.json`), "utf8"));

  // A PENDING intent with no matching commit row is the durable trace of a
  // crash inside the irreducible window — the audit signal T1's remark claims.
  const pendingOrphans = fenceLog.intents.filter(
    (i) => i.status === "PENDING" && !fenceLog.committed[i.operationId]
  ).length;
  const events = PHASES.flatMap((p) => phaseOut[p]?.events ?? []);
  const seedPid = phaseOut.seed?.pid;

  return {
    mode,
    scorer: phaseOut.replay?.scorer ?? phaseOut.crash?.scorer ?? null,
    reachedCrashPoint: phaseOut.crash?.reachedCrashPoint ?? false,
    pids: Object.fromEntries(PHASES.map((p) => [p, phaseOut[p]?.pid ?? null])),
    wiresSent: world.wires.length,
    totalWiredUSD: world.wires.reduce((s, w) => s + w.amountUSD, 0),
    receiptsSent: world.receipts.length,
    suppressions: events.filter((e) => e.type === "SUPPRESSED").length,
    suppressionLayers: events.filter((e) => e.type === "SUPPRESSED").map((e) => e.layer),
    suppressionScores: events.filter((e) => e.type === "SUPPRESSED").map((e) => e.score ?? null),
    escalated: events.some((e) => e.type === "ESCALATED"),
    windowSuspectFlagged: events.some((e) => e.type === "WINDOW_SUSPECT"),
    pendingOrphans,
    // A suppression decided by a process that shares nothing with the committer
    // but a directory on disk.
    crossProcess: events.some((e) => e.type === "SUPPRESSED" && e.pid !== seedPid),
    judgeCalls: PHASES.reduce((a, p) => a + (phaseOut[p]?.judgeCalls ?? 0), 0),
    judgeTokens: PHASES.reduce((a, p) => a + (phaseOut[p]?.judgeTokens ?? 0), 0),
    judgeLatencyMs: PHASES.reduce((a, p) => a + (phaseOut[p]?.judgeLatencyMs ?? 0), 0),
  };
}

async function main() {
  const pool = await loadParaphrasePool({ size: 40, generator: POOL_GENERATOR });
  const thresholds = calibratedThresholds();
  const judgeModel = thresholds.judge;
  const judgeFamily = JUDGE_MODELS[judgeModel]?.family ?? "unknown";
  const poolFamily = JUDGE_MODELS[pool.generator]?.family ?? pool.generator;
  process.stdout.write(
    `paraphrase pool: ${pool.pool.length} variants (generator=${pool.generator}, family=${poolFamily}, rejected=${pool.rejected})\n` +
    `thresholds: tHi=${thresholds.tHi} tLo=${thresholds.tLo} (source=${thresholds.source})\n` +
    `judge: ${live && groqAvailable() ? `${judgeModel} (family=${judgeFamily})` : "lexical-offline"}   trials=${N_TRIALS}\n` +
    `cross-family pool: ${poolFamily !== judgeFamily ? "YES" : "NO — self-recognition confound present"}\n\n`
  );
  if (pool.pool.length < 2) throw new Error("paraphrase pool needs at least 2 variants");

  // Seeded draws so the trial population is reproducible.
  let s = 20260815;
  const rnd = () => (s = (s * 1664525 + 1013904223) >>> 0) / 2 ** 32;
  const drawPair = () => {
    const i = Math.floor(rnd() * pool.pool.length);
    let j = Math.floor(rnd() * pool.pool.length);
    if (j === i) j = (j + 1) % pool.pool.length; // the two replays differ
    return [pool.pool[i], pool.pool[j]];
  };

  const trials = [];
  for (let t = 0; t < N_TRIALS; t++) {
    const [pa, pb] = drawPair();
    const spec = {
      trial: t,
      paraphraseA: pa,
      paraphraseB: pb,
      crashPoint: CRASH_POINTS[t % CRASH_POINTS.length], // balanced across points
      thresholds: { tHi: thresholds.tHi, tLo: thresholds.tLo },
      judgeModel,
      windowGuard: true,
    };
    const perMode = {};
    for (const mode of MODES) {
      perMode[mode] = runTrial(mode, resolve(base, "results", `crash-${mode}`), spec);
    }
    trials.push({ ...spec, modes: perMode });
    process.stdout.write(
      `trial ${String(t + 1).padStart(3)}/${N_TRIALS} ${spec.crashPoint.padEnd(42)} ` +
      MODES.map((m) => `${m}=$${perMode[m].totalWiredUSD}${perMode[m].reachedCrashPoint ? "" : "*"}`).join(" ") + "\n"
    );
  }

  // ── Aggregate by (crash point, mode) ───────────────────────────────────────
  const once = (rows) => rate(rows.filter((r) => r.wiresSent === 1 && r.totalWiredUSD === 780).length, rows.length);
  const summary = {};
  for (const cp of CRASH_POINTS) {
    summary[cp] = { isCommitWindow: WINDOW_POINTS.has(cp) };
    for (const mode of MODES) {
      const rows = trials.filter((t) => t.crashPoint === cp).map((t) => t.modes[mode]);
      if (rows.length === 0) continue;
      summary[cp][mode] = {
        nTrials: rows.length,
        exactlyOnceRate: once(rows),
        doubleFireRate: rate(rows.filter((r) => r.wiresSent >= 2).length, rows.length),
        meanWiredUSD: rows.reduce((a, r) => a + r.totalWiredUSD, 0) / rows.length,
        // Whether the crashing process ever got to its assigned crash point. In
        // the semantic mode the fence often settles the dispatch first, so the
        // dangerous region is never entered — an outcome, not a missing datum.
        crashPointReached: rate(rows.filter((r) => r.reachedCrashPoint).length, rows.length),
        suppressionTrials: rate(rows.filter((r) => r.suppressions > 0).length, rows.length),
        windowSuspectFlagged: rate(rows.filter((r) => r.windowSuspectFlagged).length, rows.length),
        pendingOrphanTrials: rows.filter((r) => r.pendingOrphans > 0).length,
        crossProcessSuppressions: rows.filter((r) => r.crossProcess).length,
        meanJudgeCalls: rows.reduce((a, r) => a + r.judgeCalls, 0) / rows.length,
        meanJudgeTokens: rows.reduce((a, r) => a + r.judgeTokens, 0) / rows.length,
      };
    }
  }

  const overall = {}, defensible = {}, windowOnly = {};
  for (const mode of MODES) {
    const all = trials.map((t) => t.modes[mode]);
    const def = trials.filter((t) => !WINDOW_POINTS.has(t.crashPoint)).map((t) => t.modes[mode]);
    const win = trials.filter((t) => WINDOW_POINTS.has(t.crashPoint)).map((t) => t.modes[mode]);
    const pack = (rows) => ({
      nTrials: rows.length,
      exactlyOnceRate: once(rows),
      meanWiredUSD: rows.length ? rows.reduce((a, r) => a + r.totalWiredUSD, 0) / rows.length : 0,
      totalWiredUSD: rows.reduce((a, r) => a + r.totalWiredUSD, 0),
      windowSuspectFlagged: rate(rows.filter((r) => r.windowSuspectFlagged).length, rows.length),
    });
    overall[mode] = pack(all);
    defensible[mode] = pack(def);
    windowOnly[mode] = pack(win);
  }

  const results = {
    generatedAt: new Date().toISOString(),
    live,
    nTrials: N_TRIALS,
    judge: live && groqAvailable() ? judgeModel : "lexical-offline",
    judgeFamily,
    paraphrasePool: { generator: pool.generator, family: poolFamily, size: pool.pool.length, rejected: pool.rejected },
    crossFamily: poolFamily !== judgeFamily,
    thresholds,
    crashPoints: CRASH_POINTS,
    commitWindowPoints: [...WINDOW_POINTS],
    byCrashPoint: summary,
    overall,
    defensibleOnly: defensible,
    commitWindowOnly: windowOnly,
    trials,
  };
  writeFileSync(resolve(base, "results", OUT_NAME), JSON.stringify(results, null, 2));

  // ── Report ─────────────────────────────────────────────────────────────────
  console.log("\n── exactly-once rate by crash point ──");
  for (const cp of CRASH_POINTS) {
    for (const mode of MODES) {
      const m = summary[cp]?.[mode];
      if (!m) continue;
      console.log(
        `${cp.padEnd(44)} ${mode.padEnd(10)} n=${String(m.nTrials).padStart(2)}  ` +
        `once=${fmtRate(m.exactlyOnceRate).padEnd(24)} $${m.meanWiredUSD.toFixed(0).padStart(4)}  ` +
        `reached=${fmtRate(m.crashPointReached).padEnd(22)} suppressed=${fmtRate(m.suppressionTrials)}`
      );
    }
  }
  console.log("\n── overall / excluding the commit window / inside it ──");
  for (const mode of MODES) {
    console.log(
      `${mode.padEnd(10)} all=${fmtRate(overall[mode].exactlyOnceRate).padEnd(24)} ` +
      `defensible=${fmtRate(defensible[mode].exactlyOnceRate).padEnd(24)} ` +
      `window=${fmtRate(windowOnly[mode].exactlyOnceRate).padEnd(22)} ` +
      `windowFlagged=${fmtRate(windowOnly[mode].windowSuspectFlagged)}`
    );
  }

  // The experiment's claim is comparative and scoped: semantic identity
  // strictly extends L0, so it must never be WORSE than content addressing.
  const semOnce = defensible.semantic.exactlyOnceRate.value;
  const synOnce = defensible.syntactic.exactlyOnceRate.value;
  if (semOnce < synOnce) {
    console.error(`\nEXPERIMENT FAILED — semantic (${semOnce}) regressed below syntactic (${synOnce}) outside the commit window.`);
    process.exit(1);
  }
  console.log(`\nOK — semantic ${(semOnce * 100).toFixed(1)}% vs syntactic ${(synOnce * 100).toFixed(1)}% exactly-once outside the commit window.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
