import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { GroqClient, groqAvailable } from "../groq.js";
import { extractNumbers } from "../judge.js";

/**
 * The pool of paraphrases a replaying agent might emit for one fixed wire:
 * $780 to Marlow Freight for shipment 88213.
 *
 * Randomising the replay's surface form across trials is what turns the
 * crash/replay from an anecdote into a measurement — a single hand-authored
 * paraphrase measures whether the judge handles THAT string, not whether it
 * handles paraphrase.
 *
 * The pool is generated by a model from a DIFFERENT family than the judge, for
 * the same reason the corpus carries a cross-generator arm: a judge scoring its
 * own phrasings is measuring self-recognition. Every candidate is validated to
 * preserve the act before it enters the pool — a "paraphrase" that changed the
 * amount would silently turn a correct suppression into a wrong one and
 * corrupt the experiment's ground truth.
 */

const here = dirname(fileURLToPath(import.meta.url));
const poolFile = (generator) =>
  resolve(here, "..", "..", "corpus", `wire-paraphrases-${String(generator).replace(/[^a-z0-9]+/gi, "_").toLowerCase()}.json`);

/**
 * Default pool generator. Deliberately NOT the judge used in the reported
 * crash/replay run: a judge scoring paraphrases its own family wrote is partly
 * measuring self-recognition, and the previous version of this experiment drew
 * its pool from the judge's own model while claiming otherwise.
 */
export const GENERATOR_MODEL = "llama-3.3-70b-versatile";

/** The act every pool member must denote. */
export const CANONICAL_ACT = { amountUSD: 780, beneficiary: ["marlow", "freight"], shipment: 88213 };

/**
 * Hand-authored fallback pool. Used when no API key is present so the
 * experiment still runs offline and in CI; the live path prefers generated
 * paraphrases, which are more varied than anything written by hand here.
 */
export const FALLBACK_POOL = [
  { amount_text: "seven hundred eighty dollars", beneficiary_text: "MARLOW FREIGHT", reference: "shipment #88213" },
  { amount_text: "USD 780", beneficiary_text: "Marlow Freight Ltd", reference: "ref: shipment 88213" },
  { amount_text: "780.00 US dollars", beneficiary_text: "marlow freight", reference: "for shipment no. 88213" },
  { amount_text: "$780", beneficiary_text: "Marlow  Freight", reference: "Shipment number 88213" },
  { amount_text: "seven hundred and eighty USD", beneficiary_text: "MARLOW-FREIGHT", reference: "88213 shipment" },
  { amount_text: "780 dollars exactly", beneficiary_text: "Marlow Freight Co", reference: "covering shipment 88213" },
];

/**
 * A candidate is admissible only if it denotes the same act: the amount field
 * must mention 780 and nothing else, the beneficiary must still name Marlow
 * Freight, and the reference must still cite shipment 88213.
 */
export function validParaphrase(p) {
  if (!p || typeof p !== "object") return false;
  for (const f of ["amount_text", "beneficiary_text", "reference"]) {
    if (typeof p[f] !== "string" || p[f].trim().length === 0) return false;
  }
  const amounts = extractNumbers(p.amount_text);
  if (amounts.size !== 1 || !amounts.has(CANONICAL_ACT.amountUSD)) return false;
  const ben = p.beneficiary_text.toLowerCase();
  if (!CANONICAL_ACT.beneficiary.some((t) => ben.includes(t))) return false;
  const refNums = extractNumbers(p.reference);
  if (!refNums.has(CANONICAL_ACT.shipment)) return false;
  // The replay must actually differ from the original dispatch, or the trial
  // degenerates into the L0 case the syntactic fence already handles.
  const canonicalOriginal = "$780.00|marlow freight|shipment 88213";
  const surface = `${p.amount_text}|${p.beneficiary_text}|${p.reference}`.toLowerCase().replace(/\s+/g, " ").trim();
  return surface !== canonicalOriginal;
}

const SYSTEM = `You rewrite a bank wire instruction WITHOUT changing what it does.
The wire is always: 780 US dollars, to Marlow Freight, for shipment 88213.
Rewrite the three free-text fields so the WORDING varies naturally — as different people, or the same agent on different attempts, would phrase the SAME single wire. You may spell numbers out, reorder, abbreviate, change case and punctuation.
NEVER change the amount, the beneficiary, or the shipment number. Do not introduce any other number.
Output STRICT JSON only: [{"amount_text": "...", "beneficiary_text": "...", "reference": "..."}]`;

/**
 * Build (or load) the paraphrase pool. Cached on disk so repeated experiment
 * runs draw from the same population and stay reproducible.
 */
export async function loadParaphrasePool({ size = 40, regenerate = false, generator = GENERATOR_MODEL } = {}) {
  const poolPath = poolFile(generator);
  if (!regenerate && existsSync(poolPath)) {
    const cached = JSON.parse(readFileSync(poolPath, "utf8"));
    if (Array.isArray(cached.pool) && cached.pool.length > 0) return cached;
  }
  if (generator === "handwritten" || !groqAvailable()) {
    const out = {
      generator: groqAvailable() ? "handwritten" : "handwritten-fallback",
      generatedAt: new Date().toISOString(), pool: FALLBACK_POOL, rejected: 0,
    };
    writeFileSync(poolPath, JSON.stringify(out, null, 2));
    return out;
  }

  const client = new GroqClient({ model: generator });
  const pool = [];
  const seen = new Set();
  let rejected = 0;
  const batch = 10;
  for (let round = 0; pool.length < size && round < 8; round++) {
    let json = null;
    try {
      ({ json } = await client.jsonChat({
        system: SYSTEM,
        prompt: `Produce ${batch} distinct rewrites. Vary them as much as the constraints allow. Return the JSON array now.`,
        temperature: 1.0,
        maxTokens: 900,
      }));
    } catch {
      continue; // transient model/parse failure — try another round
    }
    for (const cand of Array.isArray(json) ? json : []) {
      const norm = {
        amount_text: String(cand.amount_text ?? "").trim(),
        beneficiary_text: String(cand.beneficiary_text ?? "").trim(),
        reference: String(cand.reference ?? "").trim(),
      };
      const key = JSON.stringify(norm).toLowerCase();
      if (seen.has(key)) continue;
      if (!validParaphrase(norm)) { rejected += 1; continue; }
      seen.add(key);
      pool.push(norm);
    }
  }
  // Always keep the fallbacks in the population so the pool never collapses to
  // whatever the generator happened to favour on one day.
  for (const p of FALLBACK_POOL) {
    const key = JSON.stringify(p).toLowerCase();
    if (!seen.has(key)) { seen.add(key); pool.push(p); }
  }
  const out = { generator, generatedAt: new Date().toISOString(), pool, rejected };
  writeFileSync(poolPath, JSON.stringify(out, null, 2));
  return out;
}
