-- 0004_persistence_correctness.sql
-- Closes the schema/runtime drift discovered during the persistence
-- hardening audit. Three drift items are corrected here:
--
--   1. events.idempotency_key  — referenced by PostgresEventStore.append()
--      via ON CONFLICT (idempotency_key) but never declared in schema.sql
--      or any earlier migration. The result is that every event write in
--      Postgres mode failed with `column "idempotency_key" does not exist`.
--      We add the column, backfill historical rows from id::text (which is
--      itself unique), then add a UNIQUE constraint so ON CONFLICT works.
--
--   2. agents.model_temperature — the TS ModelConfig has an optional
--      `temperature` field that cannot be persisted to the existing
--      (model_provider, model_name) flat columns. Adding it nullable so
--      historical rows remain valid and new rows round-trip the full
--      ModelConfig shape.
--
--   3. memory_records.updated_at — the in-memory implementation never
--      tracks updates, but a durable adapter needs a deterministic update
--      column for cache invalidation and projection bookkeeping. Default
--      now() so existing rows stay valid; the column is optional from the
--      domain perspective.
--
-- Backward compatibility:
--   • All three changes are additive — no column is renamed, dropped, or
--     made stricter than the existing data supports.
--   • The UNIQUE constraint on events.idempotency_key is created after a
--     backfill so the migration never fails on legacy duplicate-free data.
--   • The migration is idempotent and re-runnable: it guards every step
--     with IF NOT EXISTS / IF EXISTS so applying it twice is a no-op.
--
-- Safety notes:
--   • The backfill uses `id::text` because event.id is already a UUID and
--     the (type, aggregateId, traceId, causationId) idempotency key for
--     new rows is sha256+base64url — the two namespaces do not collide.
--   • The UNIQUE index is created CONCURRENTLY-safe via a regular CREATE
--     UNIQUE INDEX inside the transaction; CONCURRENTLY is not used here
--     because the runtime is held offline during migration execution at
--     startup. If this migration is replayed against a live database, run
--     it during a maintenance window or split it manually.

begin;

-- ---------------------------------------------------------------------------
-- events.idempotency_key
-- ---------------------------------------------------------------------------

alter table events
  add column if not exists idempotency_key text;

-- Backfill any pre-existing rows that predate the idempotency contract.
-- id::text is globally unique and never collides with the sha256-derived
-- keys generated by EventFactory for new rows.
update events
   set idempotency_key = id::text
 where idempotency_key is null;

alter table events
  alter column idempotency_key set not null;

-- ON CONFLICT (idempotency_key) requires a UNIQUE constraint or unique
-- index on the column. Adding the constraint via DO/IF NOT EXISTS so the
-- migration is safe to re-apply.
do $$
begin
  if not exists (
    select 1 from pg_constraint
     where conname = 'events_idempotency_key_key'
  ) then
    alter table events
      add constraint events_idempotency_key_key unique (idempotency_key);
  end if;
end$$;

-- ---------------------------------------------------------------------------
-- agents.model_temperature
-- ---------------------------------------------------------------------------

alter table agents
  add column if not exists model_temperature double precision null;

-- ---------------------------------------------------------------------------
-- memory_records.updated_at
-- ---------------------------------------------------------------------------

alter table memory_records
  add column if not exists updated_at timestamptz null;

update memory_records
   set updated_at = created_at
 where updated_at is null;

-- ---------------------------------------------------------------------------
-- Minor index additions used by the new Postgres repositories
-- ---------------------------------------------------------------------------

-- Used by ExecutionRepository.listByAgent(agentId) ORDER BY started_at DESC.
create index if not exists idx_executions_agent_started
  on executions(agent_id, started_at desc);

-- Used by MemoryRepository.search() agent filter + recency tiebreak. The
-- existing idx_memory_agent_created covers (agent_id, created_at desc); we
-- keep that and add a lookup index for execution scoping, which the in-memory
-- impl supports implicitly via the records map.
create index if not exists idx_memory_execution
  on memory_records(execution_id)
  where execution_id is not null;

commit;
