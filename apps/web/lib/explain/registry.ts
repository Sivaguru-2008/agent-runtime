// ── Interpretation helpers ────────────────────────────────────────────────
// Small builders so live graph readings stay consistent across metrics.

function band(
  value: number,
  bands: { max: number; level: Interpretation["level"]; reading: string; impact?: string; recommendation?: string }[]
): Interpretation {
  for (const b of bands) {
    if (value <= b.max) {
      return { level: b.level, reading: b.reading, impact: b.impact, recommendation: b.recommendation };
    }
  }
  const last = bands[bands.length - 1];
  return { level: last.level, reading: last.reading, impact: last.impact, recommendation: last.recommendation };
}

